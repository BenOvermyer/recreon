APPENDIX_PATH = HERE / "generated" / "appendix-reference.md"
PDF_PATH = HERE / "recreon-manual.pdf"
HTML_PATH = HERE / "recreon-manual.html"

sys.path.insert(0, str(REPO / "src"))

