#!/usr/bin/env python
"""Build the Re:creon Player's Manual.

The manual's prose lives in ``chapters/`` as one Markdown file per chapter.
The appendix of reference tables is *generated* from the port's own game
tables (``recreon.datacnst``, ``recreon.attack``) so the numbers the player
reads can never silently disagree with the numbers the game uses. Then pandoc
is invoked twice: once through ``template.typ`` (typst) for the PDF, once
standalone for the HTML edition.

Usage (from the repository root)::

    uv run python docs/manual/build.py              # tables + PDF + HTML
    uv run python docs/manual/build.py --check      # verify the appendix only
    uv run python docs/manual/build.py --tables     # regenerate the appendix

``--check`` is what ``tests/test_manual.py`` runs; it needs no pandoc.
"""

